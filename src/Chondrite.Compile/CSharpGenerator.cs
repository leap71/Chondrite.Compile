using System.Globalization;
using System.Text;

namespace Chondrite.Compile;

/// <summary>Emits C# value records and code-only binary codecs for canonical schemas.</summary>
public static class CSharpGenerator
{
    /// <summary>
    /// Emits the generated, replaceable half of a partial value type. The persistent
    /// fields live exclusively inside a private nested SchemaData record.
    /// </summary>
    public static string Generate(CompiledSchema oSchema)
    {
        StringBuilder o = new();
        string[] astrName = oSchema.Name.Split('.');
        string strType = Escape(astrName[^1]);
        string strNamespace = string.Join(".", astrName[..^1].Select(Escape));
        if (strNamespace.Length == 0)
            strNamespace = "Chondrite.Generated";

        o.AppendLine("// <auto-generated />");
        o.AppendLine("#nullable enable");
        o.AppendLine("using System;");
        o.AppendLine("using System.Collections.Immutable;");
        o.AppendLine("using System.Collections.Generic;");
        o.AppendLine("using System.IO;");
        o.AppendLine("using System.Text;");
        o.AppendLine("using Chondrite.Core;");
        o.AppendLine("using Chondrite.Store;");
        o.AppendLine("using Chondrite.Store.Serialization;");
        o.AppendLine();
        o.AppendLine("namespace " + strNamespace + ";");
        o.AppendLine();

        o.AppendLine("/// <summary>Persistent state generated from an immutable schema.</summary>");
        o.AppendLine("[global::System.Runtime.InteropServices.StructLayout(global::System.Runtime.InteropServices.LayoutKind.Auto)]");
        o.AppendLine("public readonly partial record struct " + strType + " : IStorageRecord<" + strType + ">");
        o.AppendLine("{");
        o.AppendLine("    private readonly SchemaData m_oData;");
        o.AppendLine();
        if (oSchema.Fields.Count == 0)
            o.AppendLine("    private readonly record struct SchemaData { }");
        else
        {
            o.AppendLine("    private readonly record struct SchemaData(");
            for (int i = 0; i < oSchema.Fields.Count; i++)
            {
                SchemaField oField = oSchema.Fields[i];
                o.Append("        ").Append(CSharpType(oField.Type)).Append(' ')
                    .Append(Escape(oField.Name));
                o.AppendLine(i + 1 == oSchema.Fields.Count ? ");" : ",");
            }
        }
        o.AppendLine();
        o.AppendLine("    private " + strType + "(SchemaData oData) => m_oData = oData;");
        o.AppendLine();
        o.AppendLine("    internal void xWriteSchemaData(StorageBinaryWriter oWriter)");
        o.AppendLine("    {");
        o.AppendLine("        SchemaData oValue = m_oData;");
        int nSerial = 0;
        foreach (SchemaField oField in oSchema.Fields)
            EmitWrite(o, oField.Type, "oValue." + Escape(oField.Name), 8, ref nSerial);
        o.AppendLine("    }");
        o.AppendLine();
        o.AppendLine("    internal static " + strType + " oReadSchemaData(ref StorageBinaryReader oReader)");
        o.AppendLine("    {");
        nSerial = 0;
        foreach (SchemaField oField in oSchema.Fields)
            EmitRead(o, oField.Type, "oField" + oField.Index, 8, ref nSerial);
        string strFields = string.Join(", ", oSchema.Fields.Select(f => "oField" + f.Index));
        o.AppendLine("        return new " + strType + "(new SchemaData(" + strFields + "));");
        o.AppendLine("    }");
        o.AppendLine();
        o.AppendLine("    /// <summary>Identity of the exact immutable persistence schema.</summary>");
        o.AppendLine("    public static StorageType idSchema { get; } = new(");
        o.AppendLine("        new StorageObjectId(Convert.FromHexString(\"" + oSchema.Id + "\")));");
        string strEscapedCanonical = CSharpString(oSchema.CanonicalText);
        o.AppendLine("    private static readonly ImmutableArray<byte> c_abyCanonicalSchema =");
        o.AppendLine("        ImmutableArray.CreateRange(Encoding.UTF8.GetBytes(\"" + strEscapedCanonical + "\"));");
        o.AppendLine();
        o.AppendLine("    /// <summary>Idempotently publishes this schema and its dependencies.</summary>");
        o.AppendLine("    public static void EnsureSchema(IObjectStore oStore)");
        o.AppendLine("    {");
        o.AppendLine("        ArgumentNullException.ThrowIfNull(oStore);");
        foreach (string strDep in oSchema.Dependencies)
            o.AppendLine("        " + Qualified(strDep) + ".EnsureSchema(oStore);");
        o.AppendLine("        if (oStore.idRegisterType(c_abyCanonicalSchema) != idSchema)");
        o.AppendLine("            throw new InvalidDataException(\"Schema identity mismatch.\");");
        o.AppendLine("    }");
        o.AppendLine();
        o.AppendLine("    public static StorageObject oSerialize(in " + strType + " oValue)");
        o.AppendLine("    {");
        o.AppendLine("        StorageBinaryWriter oWriter = new();");
        o.AppendLine("        xWrite(oWriter, in oValue);");
        o.AppendLine("        return new StorageObject(idSchema, ImmutableArray.CreateRange(oWriter.aToArray()));");
        o.AppendLine("    }");
        o.AppendLine();
        o.AppendLine("    public static " + strType + " oDeserialize(StorageObject oObject)");
        o.AppendLine("        => oDeserialize(oObject, StorageDecodeLimits.oDefault);");
        o.AppendLine();
        o.AppendLine("    /// <summary>Decodes using limits scoped to this top-level record.</summary>");
        o.AppendLine("    public static " + strType + " oDeserialize(StorageObject oObject, StorageDecodeLimits oLimits)");
        o.AppendLine("    {");
        o.AppendLine("        ArgumentNullException.ThrowIfNull(oObject);");
        o.AppendLine("        if (oObject.idType != idSchema)");
        o.AppendLine("            throw new InvalidDataException(\"Unexpected persistence schema.\");");
        o.AppendLine("        StorageBinaryReader oReader = new(oObject.abyData.AsSpan(), oLimits);");
        o.AppendLine("        " + strType + " oValue = oRead(ref oReader);");
        o.AppendLine("        oReader.EnsureEnd();");
        o.AppendLine("        return oValue;");
        o.AppendLine("    }");
        o.AppendLine();
        o.AppendLine("    public static StorageObjectId idPut(IObjectStore oStore, in " + strType +
            " oValue, StorageObjectId? idPredecessorHint = null)");
        o.AppendLine("    {");
        o.AppendLine("        EnsureSchema(oStore);");
        o.AppendLine("        return oStore.idPut(oSerialize(in oValue), idPredecessorHint);");
        o.AppendLine("    }");
        o.AppendLine();
        o.AppendLine("    public static " + strType + " oGet(IObjectStore oStore, StorageObjectId idObject)");
        o.AppendLine("    {");
        o.AppendLine("        StorageObject oObject = oStore.oGet(idObject) ?? throw new KeyNotFoundException();");
        o.AppendLine("        return oDeserialize(oObject);");
        o.AppendLine("    }");
        o.AppendLine();
        o.AppendLine("    /// <summary>Writes this record inline; nested records have no envelope.</summary>");
        o.AppendLine("    public static void xWrite(StorageBinaryWriter oWriter, in " + strType + " oValue)");
        o.AppendLine("        => oValue.xWriteSchemaData(oWriter);");
        o.AppendLine();
        o.AppendLine("    /// <summary>Reads this record inline; the caller supplies the schema context.</summary>");
        o.AppendLine("    public static " + strType + " oRead(ref StorageBinaryReader oReader)");
        o.AppendLine("        => oReadSchemaData(ref oReader);");
        o.AppendLine("}");
        return o.ToString().Replace("\r\n", "\n");
    }

    /// <summary>
    /// Emits an editable partial declaration exactly once. It is a convenience API,
    /// not part of the immutable published schema and never used by the codec.
    /// </summary>
    public static string GenerateEditable(CompiledSchema oSchema)
    {
        StringBuilder o = new();
        string[] astrName = oSchema.Name.Split('.');
        string strType = Escape(astrName[^1]);
        string strNamespace = string.Join(".", astrName[..^1].Select(Escape));
        if (strNamespace.Length == 0)
            strNamespace = "Chondrite.Generated";

        o.AppendLine("// User-editable partial declaration. The schema compiler never overwrites this file.");
        o.AppendLine("#nullable enable");
        o.AppendLine("using System;");
        o.AppendLine("using System.Collections.Immutable;");
        o.AppendLine();
        o.AppendLine("namespace " + strNamespace + ";");
        o.AppendLine();
        o.AppendLine("public readonly partial record struct " + strType);
        o.AppendLine("{");
        if (oSchema.Fields.Count > 0)
        {
            o.Append("    public ").Append(strType).AppendLine("(");
            for (int i = 0; i < oSchema.Fields.Count; i++)
            {
                SchemaField oField = oSchema.Fields[i];
                o.Append("        ").Append(CSharpType(oField.Type)).Append(' ')
                    .Append(Escape(oField.Name));
                o.AppendLine(i + 1 == oSchema.Fields.Count ? ")" : ",");
            }
            string strArgs = string.Join(", ", oSchema.Fields.Select(f => Escape(f.Name)));
            o.AppendLine("    {");
            o.AppendLine("        m_oData = new SchemaData(" + strArgs + ");");
            o.AppendLine("    }");
            o.AppendLine();
            foreach (SchemaField oField in oSchema.Fields)
            {
                // A member cannot have the same identifier as its enclosing C# type.
                string strPropertyName = oField.Name;
                while (strPropertyName == astrName[^1] || c_astrGeneratedMembers.Contains(strPropertyName))
                    strPropertyName = "field_" + strPropertyName;
                o.Append("    public ").Append(CSharpType(oField.Type)).Append(' ')
                    .Append(Escape(strPropertyName)).Append(" => m_oData.")
                    .Append(Escape(oField.Name)).AppendLine(";");
            }
        }
        o.AppendLine("}");
        return o.ToString().Replace("\r\n", "\n");
    }

    // The generated partial already declares these members; editable accessors
    // must not accidentally shadow them if a schema field shares a name.
    private static readonly HashSet<string> c_astrGeneratedMembers = new(StringComparer.Ordinal)
    {
        "SchemaData", "m_oData", "idSchema", "c_abyCanonicalSchema",
        "EnsureSchema", "oSerialize", "oDeserialize", "idPut", "oGet",
        "xWrite", "oRead", "xWriteSchemaData", "oReadSchemaData"
    };

    // Only reserved C# keywords require escaping here. Contextual keywords such
    // as 'value' and 'record' are legal as ordinary member/type identifiers.
    private static readonly HashSet<string> c_astrKeywords = new(StringComparer.Ordinal)
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch",
        "char", "checked", "class", "const", "continue", "decimal", "default",
        "delegate", "do", "double", "else", "enum", "event", "explicit",
        "extern", "false", "finally", "fixed", "float", "for", "foreach",
        "goto", "if", "implicit", "in", "int", "interface", "internal",
        "is", "lock", "long", "namespace", "new", "null", "object",
        "operator", "out", "override", "params", "private", "protected",
        "public", "readonly", "ref", "return", "sbyte", "sealed", "short",
        "sizeof", "stackalloc", "static", "string", "struct", "switch",
        "this", "throw", "true", "try", "typeof", "uint", "ulong",
        "unchecked", "unsafe", "ushort", "using", "virtual", "void",
        "volatile", "while"
    };

    private static string Escape(string str) =>
        str == "_" || c_astrKeywords.Contains(str) ? "@" + str : str;

    private static string Qualified(string strName) =>
        "global::" + string.Join(".", strName.Split('.').Select(Escape));

    private static string CSharpString(string str) => str.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", "\\n");

    private static string CSharpType(SchemaType oType) => oType switch
    {
        PrimitiveType oPrimitive => PrimitiveCatalog.Get(oPrimitive.Name).CSharpType,
        ReferenceType oRef => Qualified(oRef.Name),
        ArrayType oArr => "ImmutableArray<" + CSharpType(oArr.Element) + ">",
        OptionalType oOpt => CSharpType(oOpt.Inner) + "?",
        _ => throw new NotSupportedException()
    };

    private static void Line(StringBuilder o, int nIndent, string strLine) =>
        o.Append(' ', nIndent).AppendLine(strLine);

    private static void EmitWrite(StringBuilder o, SchemaType oType, string strValue,
        int nIndent, ref int nSerial)
    {
        if (oType is PrimitiveType oPrimitive)
        {
            PrimitiveDescriptor oDescriptor = PrimitiveCatalog.Get(oPrimitive.Name);
            string strArgument = strValue;
            if (oDescriptor.WriteByteSpan)
            {
                Line(o, nIndent, "if (" + strValue + ".IsDefault)");
                Line(o, nIndent + 4, "throw new InvalidDataException(\"Uninitialized byte array.\");");
                strArgument += ".AsSpan()";
            }
            Line(o, nIndent, "oWriter." + oDescriptor.WriterMethod + "(" + strArgument + ");");
        }
        else if (oType is ReferenceType oRef)
            Line(o, nIndent, Qualified(oRef.Name) + ".xWrite(oWriter, " + strValue + ");");
        else if (oType is ArrayType oArray)
        {
            int n = nSerial++;
            string strIt = "oElement" + n;
            Line(o, nIndent, "if (" + strValue + ".IsDefault)");
            Line(o, nIndent + 4, "throw new InvalidDataException(\"Uninitialized array.\");");
            if (oArray.FixedCount is ulong nFixed)
            {
                if (nFixed > int.MaxValue)
                    throw new FormatException("Fixed arrays larger than int.MaxValue are unsupported in C#.");
                Line(o, nIndent, "if ((ulong)" + strValue + ".Length != " + nFixed.ToString(CultureInfo.InvariantCulture) + "UL)");
                Line(o, nIndent + 4, "throw new InvalidDataException(\"Fixed-array length mismatch.\");");
            }
            else
                Line(o, nIndent, "oWriter.WriteUInt64((ulong)" + strValue + ".Length);");
            Line(o, nIndent, "foreach (" + CSharpType(oArray.Element) + " " + strIt + " in " + strValue + ")");
            Line(o, nIndent, "{");
            EmitWrite(o, oArray.Element, strIt, nIndent + 4, ref nSerial);
            Line(o, nIndent, "}");
        }
        else if (oType is OptionalType oOptional)
        {
            int n = nSerial++;
            string strInner = "oPresent" + n;
            Line(o, nIndent, "if (" + strValue + " is { } " + strInner + ")");
            Line(o, nIndent, "{");
            Line(o, nIndent + 4, "oWriter.WriteBool(true);");
            EmitWrite(o, oOptional.Inner, strInner, nIndent + 4, ref nSerial);
            Line(o, nIndent, "}");
            Line(o, nIndent, "else oWriter.WriteBool(false);");
        }
    }

    // Provable minimum wire width, never a heuristic. A referenced schema may
    // contain no fields, so its conservative bound is zero.
    private static int MinimumElementBytes(SchemaType oType) => oType switch
    {
        PrimitiveType oPrimitive => PrimitiveCatalog.Get(oPrimitive.Name).MinimumEncodedBytes,
        ReferenceType => 0,
        OptionalType => 1,
        ArrayType oArray when oArray.FixedCount is ulong nCount => MinimumFixedArrayBytes(oArray.Element, nCount),
        ArrayType => 8, // Variable arrays always include an eight-byte count.
        _ => throw new NotSupportedException($"Unsupported schema type '{oType}'.")
    };

    private static int MinimumFixedArrayBytes(SchemaType oElement, ulong nCount)
    {
        int nWidth = MinimumElementBytes(oElement);
        // Keep a conservative zero bound if the product cannot be passed as an int.
        if (nWidth == 0 || nCount > (ulong)(int.MaxValue / nWidth))
            return 0;
        return (int)nCount * nWidth;
    }

    private static void EmitRead(StringBuilder o, SchemaType oType, string strTarget,
        int nIndent, ref int nSerial)
    {
        string strType = CSharpType(oType);
        if (oType is PrimitiveType oPrimitive)
        {
            string strMethod = PrimitiveCatalog.Get(oPrimitive.Name).ReaderMethod;
            Line(o, nIndent, strType + " " + strTarget + " = oReader." + strMethod + "();");
        }
        else if (oType is ReferenceType oRef)
            Line(o, nIndent, strType + " " + strTarget + " = " + Qualified(oRef.Name) + ".oRead(ref oReader);");
        else if (oType is ArrayType oArr)
        {
            int n = nSerial++;
            string strCount = "nCount" + n;
            string strBuilder = "oBuilder" + n;
            string strIndex = "i" + n;
            string strElement = "oElement" + n;
            if (oArr.FixedCount is ulong nFixed)
            {
                if (nFixed > int.MaxValue)
                    throw new FormatException("Fixed arrays larger than int.MaxValue are unsupported in C#.");
                Line(o, nIndent, "int " + strCount + " = " + nFixed.ToString(CultureInfo.InvariantCulture) + ";");
            }
            else
                Line(o, nIndent, "int " + strCount + " = oReader.ReadCount();");
            // The guard must run before allocating the builder. A zero lower bound
            // is conservative for nested records, whose codecs may be empty.
            Line(o, nIndent, "oReader.GuardCollectionCount(" + strCount + ", " +
                MinimumElementBytes(oArr.Element).ToString(CultureInfo.InvariantCulture) + ");");
            Line(o, nIndent, "var " + strBuilder + " = ImmutableArray.CreateBuilder<" + CSharpType(oArr.Element) + ">(" + strCount + ");");
            Line(o, nIndent, "for (int " + strIndex + " = 0; " + strIndex + " < " + strCount + "; " + strIndex + "++)");
            Line(o, nIndent, "{");
            EmitRead(o, oArr.Element, strElement, nIndent + 4, ref nSerial);
            Line(o, nIndent + 4, strBuilder + ".Add(" + strElement + ");");
            Line(o, nIndent, "}");
            Line(o, nIndent, strType + " " + strTarget + " = " + strBuilder + ".MoveToImmutable();");
        }
        else if (oType is OptionalType oOptional)
        {
            int n = nSerial++;
            string strInner = "oInner" + n;
            Line(o, nIndent, strType + " " + strTarget + ";");
            Line(o, nIndent, "if (oReader.ReadBool())");
            Line(o, nIndent, "{");
            EmitRead(o, oOptional.Inner, strInner, nIndent + 4, ref nSerial);
            Line(o, nIndent + 4, strTarget + " = " + strInner + ";");
            Line(o, nIndent, "}");
            Line(o, nIndent, "else " + strTarget + " = null;");
        }
    }
}
